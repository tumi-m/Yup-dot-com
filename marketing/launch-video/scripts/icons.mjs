// Copies the Lucide icon shapes the film uses out of the app's lucide-react
// package into film/src/icons.js, so the film needs no React at all.
// Run from marketing/launch-video:  node scripts/icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const lucide = join(here, "../../../node_modules/lucide-react");
const version = JSON.parse(readFileSync(join(lucide, "package.json"), "utf8")).version;

const NAMES = `file-text presentation gallery-horizontal-end clapperboard arrow-left x file pen-line
signature minimize-2 file-sliders messages-square scan-text scissors lock sparkles download rotate-ccw
check cloud-upload mouse-pointer-2 type sticky-note highlighter underline strikethrough pen eraser
square circle minus arrow-up-right image link-2 text-cursor-input square-check circle-dot undo-2
redo-2 save panel-left arrow-up pencil-ruler file-down film music-2 clipboard-paste copy trash-2
arrow-down file-plus-2 chevron-left chevron-right zoom-in zoom-out trending-down`.split(/\s+/).filter(Boolean);

const out = {};
for (const name of NAMES) {
  const src = readFileSync(join(lucide, "dist/esm/icons", `${name}.js`), "utf8");
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
  if (!m) throw new Error(`no icon node in ${name}`);
  const node = Function(`return ${m[1]}`)();
  out[name] = node.map(([tag, attrs]) => {
    const a = { ...attrs };
    delete a.key;
    return [tag, a];
  });
}

const header = `/*
 * Icon shapes from Lucide (lucide-react ${version}), ISC License.
 * Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of
 * Feather (MIT). All other copyright (c) for Lucide are held by Lucide Contributors 2022.
 * Generated by scripts/icons.mjs. Do not edit by hand.
 */
`;
writeFileSync(join(here, "../film/src/icons.js"), `${header}window.ICONS = ${JSON.stringify(out)};\n`);
console.log(`wrote ${NAMES.length} icons`);
